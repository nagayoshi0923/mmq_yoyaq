// 不正なUnicode文字（壊れたサロゲートペア）を除去する関数
export const sanitizeText = (text: string | null | undefined): string => {
  if (!text) return ''
  // サロゲートペアの壊れた文字を除去
   
  return text.replace(/[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/g, '')
}

